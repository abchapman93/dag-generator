// model -> self-contained HTML document (SVG + title + legend). No external
// assets — safe to open with file:// or drop into a webpage. Used by the
// `html` export format.

import { toSVG } from './svg.mjs';

const LEGEND = {
  informal: [
    ['#dae8fc', '#6c8ebf', 'Exposure / treatment'],
    ['#fff2cc', '#d6b656', 'Outcome'],
    ['#d5e8d4', '#82b366', 'Confounder / covariate'],
    ['#e1d5e7', '#9673a6', 'Mediator'],
    ['#f8d7da', '#c0392b', 'Collider / selection'],
    ['#f0f0f0', '#999999', 'Unmeasured / latent'],
  ],
  manuscript: [
    ['#ffffff', '#1a1c22', 'Conditioning / adjustment (box)'],
    ['#ffffff', '#8a8f98', 'Unobserved (gray)'],
    ['#ffffff', '#e07a1f', 'Regime / decision (SWIG)'],
  ],
};

export function toHTML(model, opts = {}) {
  const mode = opts.style || model.meta?.style || 'informal';
  const title = model.meta?.title || 'Causal diagram';
  const svg = toSVG(model, { style: mode, background: 'transparent' });
  const legend = (LEGEND[mode] || [])
    .map(([fill, stroke, label]) => `<li><span class="sw" style="background:${fill};border-color:${stroke}"></span>${esc(label)}</li>`)
    .join('');

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>
  body{margin:0;font:15px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;color:#1a1c22;background:#fff;padding:28px}
  .wrap{max-width:900px;margin:0 auto}
  h1{font-size:19px;font-weight:650;margin:0 0 4px}
  .fig{border:1px solid #e6e8ec;border-radius:12px;padding:18px;background:#fff;overflow:auto}
  svg{max-width:100%;height:auto;display:block;margin:0 auto}
  ul.legend{list-style:none;padding:0;margin:16px 0 0;display:flex;flex-wrap:wrap;gap:10px 18px;font-size:13px;color:#4b5563}
  ul.legend li{display:flex;align-items:center;gap:7px}
  .sw{width:15px;height:12px;border-radius:3px;border:1.5px solid #999;display:inline-block}
  footer{margin-top:14px;color:#9aa0a6;font-size:12px}
</style></head>
<body><div class="wrap">
  <h1>${esc(title)}</h1>
  <div class="fig">${svg}</div>
  ${legend ? `<ul class="legend">${legend}</ul>` : ''}
  <footer>Generated by dag-generator · ${mode} style</footer>
</div></body></html>`;
}

function esc(s) {
  return String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
}
